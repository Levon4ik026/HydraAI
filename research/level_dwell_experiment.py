#!/usr/bin/env python3
"""Causal M1 level-dwell experiment on Dukascopy EURUSD BID.

A level is frozen when price first closes within 0.05 ATR(14) of the
preceding 60-minute high/low. At 5 and 30 consecutive minutes in that band,
we measure subsequent 5/10/15-minute directional outcomes. One observation
per touch/threshold/side; no future data enters the trigger.
"""
from __future__ import annotations
import argparse, math
from collections import defaultdict
from pathlib import Path
from datetime import timedelta
from long_history_validation import read_duka, PAYOUT

def segments(rows):
    out=[]; cur=[]
    for b in rows:
        if cur and b.timestamp-cur[-1].timestamp != timedelta(minutes=1):
            if len(cur)>80: out.append(cur)
            cur=[]
        cur.append(b)
    if len(cur)>80: out.append(cur)
    return out

def atr_at(bars,i):
    trs=[]
    for j in range(i-13,i+1):
        p=bars[j-1].close
        b=bars[j]
        trs.append(max(b.high-b.low,abs(b.high-p),abs(b.low-p)))
    return sum(trs)/14

def stats(rs):
    w=sum(x=="WIN" for x in rs); l=sum(x=="LOSS" for x in rs); d=len(rs)-w-l
    dec=w+l
    return w,l,d,(100*w/dec if dec else float("nan")),w*PAYOUT-l

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--data",type=Path,required=True)
    ap.add_argument("--out",type=Path,required=True)
    a=ap.parse_args()
    raw=read_duka(a.data); segs=segments(raw)
    events=[]
    for sid,bars in enumerate(segs):
        # Separate resistance and support touches. Freeze level and ATR at touch start.
        for side in ("RESISTANCE","SUPPORT"):
            active=None
            for i in range(60,len(bars)-16):
                b=bars[i]
                if active is None:
                    prior=bars[i-60:i]
                    level=max(x.high for x in prior) if side=="RESISTANCE" else min(x.low for x in prior)
                    atr=atr_at(bars,i)
                    band=max(atr*0.05,1e-8)
                    if abs(b.close-level)<=band:
                        active={"level":level,"band":band,"start":i,"last":i}
                else:
                    if abs(b.close-active["level"])<=active["band"]:
                        active["last"]=i
                    else:
                        active=None
                if active is not None:
                    dwell=i-active["start"]+1
                    for threshold in (5,30):
                        key=f"fired{threshold}"
                        if dwell==threshold and not active.get(key):
                            active[key]=True
                            for h in (5,10,15):
                                entry=bars[i].close
                                exitp=bars[i+h].close
                                signed=(exitp-entry)*(1 if side=="RESISTANCE" else -1)
                                outcome="DRAW" if abs(signed)<1e-12 else "WIN" if signed>0 else "LOSS"
                                breakout=(exitp>active["level"]+active["band"]) if side=="RESISTANCE" else (exitp<active["level"]-active["band"])
                                events.append({"side":side,"threshold":threshold,"h":h,"outcome":outcome,"breakout":breakout})
    lines=[
      "# HYDRA — M1 level dwell experiment",
      "",
      f"Source: Dukascopy EURUSD M1 BID; raw rows={len(raw):,}; continuous segments={len(segs):,}; coverage={raw[0].timestamp.isoformat()} to {raw[-1].timestamp.isoformat()}.",
      "Causal definition: freeze previous-60-minute high/low and ATR(14) at first M1 close within 0.05 ATR of the level. Dwell is consecutive M1 closes inside that frozen band. Observe at exactly 5 or 30 minutes; entry proxy is that close; outcomes measured 5/10/15 minutes later.",
      f"Total observations={len(events):,}. A level touch can contribute both threshold observations. No interpolation across gaps. Payout accounting +0.92/-1/0. External BID proxy, not Pocket Option quotes.",
      "",
      "| Side | Dwell | Horizon | n | W/L/D | Decisive WR | Net u | Break-through rate |",
      "|---|---:|---:|---:|---|---:|---:|---:|"
    ]
    for side in ("RESISTANCE","SUPPORT"):
      for threshold in (5,30):
       for h in (5,10,15):
        sub=[e for e in events if e["side"]==side and e["threshold"]==threshold and e["h"]==h]
        w,l,d,wr,net=stats([e["outcome"] for e in sub])
        br=100*sum(e["breakout"] for e in sub)/len(sub) if sub else float("nan")
        lines.append(f"| {side} | {threshold}m | {h}m | {len(sub)} | {w}/{l}/{d} | {wr:.2f}% | {net:+.2f} | {br:.2f}% |")
    lines += [
      "",
      "## Interpretation limits",
      "- Exploratory descriptive test, not a validated strategy; thresholds are predeclared but multiple horizons/sides are shown.",
      "- The 5m and 30m observations are not independent when generated by the same touch; do not compare them as independent samples.",
      "- Level definition is a rolling prior-hour extreme, not a broker-provided institutional level.",
      "- A breakout frequency is not the same as binary-option win rate. Win rate uses close-to-close direction from the threshold bar.",
      "- Dukascopy BID differs from Pocket Option quotes and payout can vary. No live trading or production integration."
    ]
    a.out.parent.mkdir(parents=True,exist_ok=True)
    report="\n".join(lines)+"\n"; a.out.write_text(report,encoding="utf-8"); print(report)
if __name__=="__main__": main()
